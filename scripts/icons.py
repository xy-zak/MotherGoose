#!/usr/bin/env python3
"""Builds web/icons.svg, a sprite of the Iconoir icons MotherGoose uses.

Usage: python3 -I scripts/icons.py <path to an unpacked iconoir npm package>

Get the package from the npm registry (check its dist.integrity), unpack it
somewhere outside the repo, and point this script at the "package" folder.
Each icon becomes <symbol id="NAME">, used as <svg><use href="/_mg/icons.svg#NAME">.
Strokes use currentColor; stroke width and fill are set in theme.css.
"""
import re
import sys
from pathlib import Path

# MotherGoose name -> Iconoir name
ICONS = {
    "live": "play", "end": "log-out", "view": "eye", "edit": "edit-pencil", "folder": "folder",
    "info": "info-circle", "delete": "trash", "add": "plus", "more": "more-horiz",
    "to-referee": "arrow-right", "to-players": "arrow-left",
    "open": "open-new-window", "export": "download", "reset": "undo", "upload": "upload",
    "kind-html": "page-edit", "kind-pdf": "journal-page", "kind-image": "media-image",
    "join": "qr-code", "players": "group", "referee": "user-crown",
    "settings": "settings", "help": "help-circle", "dashboard": "dashboard",
    "full": "expand", "shrink": "collapse", "zoom-in": "zoom-in", "zoom-out": "zoom-out",
    "prev": "nav-arrow-left", "next": "nav-arrow-right", "fit": "frame-simple",
    "tag": "label", "text": "align-left", "close": "xmark", "theme": "palette",
    "font": "text-size", "game": "hexagon-dice", "data": "database", "server": "wifi",
    "check": "check", "warning": "warning-triangle", "sessions": "book-stack",
    "labels": "text-square", "light": "sun-light", "dark": "half-moon",
    # per-player pages: one person, adding / removing one, switching who you are
    "player": "user", "add-player": "user-plus", "remove-player": "user-xmark",
    "switch": "refresh-double", "template": "page",
}

def main(pkg: Path) -> None:
    src = pkg / "icons" / "regular"
    version = re.search(r'"version":\s*"([^"]+)"', (pkg / "package.json").read_text()).group(1)
    out = [
        '<svg xmlns="http://www.w3.org/2000/svg">',
        f"<!-- Iconoir {version} (MIT, https://iconoir.com). Generated by scripts/icons.py. -->",
    ]
    missing = []
    for name, icon in sorted(ICONS.items()):
        f = src / f"{icon}.svg"
        if not f.exists():
            missing.append(icon)
            continue
        svg = f.read_text()
        view = re.search(r'viewBox="([^"]+)"', svg).group(1)
        inner = re.sub(r"^.*?<svg[^>]*>|</svg>\s*$", "", svg, flags=re.S).strip()
        inner = re.sub(r"\s*\n\s*", "", inner)
        out.append(f'<symbol id="{name}" viewBox="{view}">{inner}</symbol>')
    out.append("</svg>\n")
    if missing:
        sys.exit("not in this Iconoir version: " + ", ".join(missing))
    dest = Path(__file__).resolve().parent.parent / "web" / "icons.svg"
    dest.write_text("\n".join(out))
    print(f"wrote {dest} ({len(ICONS)} icons, Iconoir {version})")

if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(Path(sys.argv[1]))
